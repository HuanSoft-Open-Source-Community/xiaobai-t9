local function split(s)
  local out = {}
  for w in s:gmatch('%S+') do out[#out+1] = w end
  return out
end

local cache = {}
local function emojis(text)
  local hit = cache[text]
  if hit == nil then
    local raw = table_[text]
    hit = raw and split(raw) or false
    cache[text] = hit
  end
  return hit
end

local M = {}

function M.func(input, env)
  -- 先把候选收完再吐，边迭代边 yield 会让同一候选被吐两次
  local all = {}
  for cand in input:iter() do all[#all + 1] = cand end
  for _, cand in ipairs(all) do
    yield(cand)
    local list = emojis(cand.text)
    if list then
      for i, e in ipairs(list) do
        if i > 4 then break end
        local c = Candidate('emoji', cand.start, cand._end, e, cand.text)
        c.quality = (cand.quality or 0) - 0.001 * i
        yield(c)
      end
    end
  end
end

return M